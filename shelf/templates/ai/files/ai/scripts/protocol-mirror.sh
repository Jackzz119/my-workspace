#!/usr/bin/env bash
#
# protocol-mirror.sh —— 根目录协议副本（CLAUDE.md / AGENTS.md）与正本（<ai>/jaAgents/ 同名文件）永远一致。
# AI 工作流模板（货架 templates/ai）的一部分，由 shelf init 装到 <ai>/scripts/。两种用法：
#
#   bash <ai>/scripts/protocol-mirror.sh --sync [--agent claude|codex|all] [--dry-run]
#       给 sync-worktree.sh 用：逐份对齐副本，打印给人看的一行结论
#   bash <ai>/scripts/protocol-mirror.sh --hook
#       Claude Code 的 SessionStart / UserPromptSubmit 钩子（模板的 .claude/settings.json 已配好）：
#       对齐 CLAUDE.md，并在本会话读到的协议已经过期时提醒重读。打印的内容会进入模型上下文；没事时什么都不打印
#
# 规则（用户 2026-10-26 定：根副本和正本永远一致，没有「追加」）：
#   - 副本不存在 → 从正本创建
#   - 副本 = 正本 → 不动
#   - 正本更新了、副本没被人动过（等于上次同步时记下的指纹，或等于正本的某个历史版本）→ 用正本覆盖副本
#   - 副本被人改过 → 两份都不动，报告：先把 diff 给用户看，用户确认后才同步回正本并 shelf push；
#     不要副本的改动 → 用户确认后加 --take-source 用正本覆盖
#   - Multica 由 bootstrap.sh 生成的协议（首行带生成标记）不归这里管
# 指纹记在本检出自己的 git 目录里（<git-dir>/ai-mirror/），不进提交、不用 gitignore；每个 worktree 各一份。
set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd -P)"   # <ai>/scripts/ → 仓库根
cd "$ROOT" || exit 0
AI_DIR="$(sed -n 's/^[[:space:]]*"aiDir"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p' .shelf.json 2>/dev/null | head -n 1 || true)"
[[ -n "$AI_DIR" ]] || AI_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && basename "$(pwd -P)")"
GIT_DIR="$(git rev-parse --git-dir 2>/dev/null)" || exit 0
STATE="$GIT_DIR/ai-mirror"

MODE=""; AGENT="all"; DRY=0; TAKE=0
while [[ $# -gt 0 ]]; do
  case "$1" in
    --sync) MODE="sync"; shift ;;
    --hook) MODE="hook"; shift ;;
    --agent) AGENT="${2:-}"; shift 2 ;;
    --agent=*) AGENT="${1#*=}"; shift ;;
    --dry-run) DRY=1; shift ;;
    --take-source) TAKE=1; shift ;;
    -h|--help) sed -n '2,24p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "✗ 未知参数：$1（用 --help 看用法）"; exit 2 ;;
  esac
done
[[ -n "$MODE" ]] || { echo "✗ 要给 --sync 或 --hook（用 --help 看用法）"; exit 2; }

sha_of() { git hash-object "$1" 2>/dev/null; }
record() { (( DRY )) && return 0; mkdir -p "$STATE" && sha_of "$1" > "$STATE/$1.sha"; }
# 副本是不是正本的某个历史版本（正本改过之后、副本还没跟上的那种旧副本）
past_source() {   # past_source <副本指纹> <正本路径>
  local commit
  while IFS= read -r commit; do
    [[ "$(git rev-parse -q --verify "$commit:$2" 2>/dev/null)" == "$1" ]] && return 0
  done < <(git log --format=%H -n 300 -- "$2" 2>/dev/null)
  return 1
}

# 对齐一份副本。结果写进 RESULT：same / created / refreshed / drift / multica / nosource
mirror_doc() {
  local name="$1" src="$AI_DIR/jaAgents/$1" sha
  if [[ ! -f "$src" ]]; then RESULT="nosource"; return; fi
  if [[ -f "$name" ]] && head -n 1 "$name" | grep -qE "generated by [^ ]*/(scripts|jaAgents)/bootstrap\.sh"; then
    RESULT="multica"; return
  fi
  if [[ ! -e "$name" ]]; then
    (( DRY )) || cp "$src" "$name"; record "$name"; RESULT="created"; return
  fi
  if cmp -s "$src" "$name"; then record "$name"; RESULT="same"; return; fi
  sha="$(sha_of "$name")"
  if (( TAKE )) || [[ "$(cat "$STATE/$name.sha" 2>/dev/null)" == "$sha" ]] || past_source "$sha" "$src"; then
    (( DRY )) || cp "$src" "$name"; record "$name"; RESULT="refreshed"; return
  fi
  RESULT="drift"
}

if [[ "$MODE" == "sync" ]]; then
  case "$AGENT" in
    claude) NAMES=("CLAUDE.md") ;; codex) NAMES=("AGENTS.md") ;; all) NAMES=("CLAUDE.md" "AGENTS.md") ;;
    *) echo "✗ --agent 只接受 claude / codex / all，收到：$AGENT"; exit 2 ;;
  esac
  drift=0
  for name in "${NAMES[@]}"; do
    mirror_doc "$name"
    case "$RESULT" in
      same) echo "= ${name} 和正本 $AI_DIR/jaAgents/$name 一致" ;;
      created) echo "✓ 创建 ${name}（来自正本 $AI_DIR/jaAgents/${name}）$( ((DRY)) && echo '（dry-run）')" ;;
      refreshed) echo "↻ ${name} 是没人改过的旧副本，已换成最新正本$( ((DRY)) && echo '（dry-run）')" ;;
      multica) echo "= ${name} 是 Multica bootstrap 生成的协议，不归这里管" ;;
      nosource) echo "⚠ 正本 $AI_DIR/jaAgents/$name 不存在，跳过 ${name}" ;;
      drift)
        drift=1
        echo "⚠ ${name} 和正本 $AI_DIR/jaAgents/$name 不一致，而且副本被人改过：两份都没动。"
        echo "  先把差异给用户看：git diff --no-index $AI_DIR/jaAgents/$name $name"
        echo "  用户确认要留副本的改动 → 复制回正本，再 shelf push $AI_DIR/jaAgents/$name（推货架前同样先看清单）；"
        echo "  用户确认不要 → bash $AI_DIR/scripts/protocol-mirror.sh --sync --agent $( [[ $name == CLAUDE.md ]] && echo claude || echo codex) --take-source"
        ;;
    esac
  done
  exit $(( drift ? 1 : 0 ))
fi

# ---------- 钩子 ----------
INPUT="$(cat 2>/dev/null || true)"
field() { printf '%s' "$INPUT" | sed -n "s/.*\"$1\"[[:space:]]*:[[:space:]]*\"\([^\"]*\)\".*/\1/p" | head -n 1; }
SESSION="$(field session_id | tr -cd 'A-Za-z0-9_-')"
EVENT="$(field hook_event_name)"
NAME="CLAUDE.md"
[[ -f "$AI_DIR/jaAgents/$NAME" ]] || exit 0

before="$(sha_of "$NAME" 2>/dev/null || true)"
mirror_doc "$NAME"
after="$(sha_of "$NAME" 2>/dev/null || true)"
[[ "$RESULT" == "multica" || "$RESULT" == "nosource" ]] && exit 0

mkdir -p "$STATE"
SESSION_FILE="$STATE/session-${SESSION:-unknown}"
loaded=""
if [[ "$EVENT" == "SessionStart" ]]; then
  loaded="$before"                       # 会话开场读到的是对齐之前那一版
  # 只留最近 50 个会话的记录
  ls -t "$STATE"/session-* 2>/dev/null | tail -n +51 | while IFS= read -r old; do rm -f "$old"; done
else
  loaded="$(cat "$SESSION_FILE" 2>/dev/null || true)"
  [[ -n "$loaded" ]] || loaded="$after"  # 钩子装上之前就开着的会话：从现在起算
fi

if [[ "$RESULT" == "drift" ]]; then
  if [[ "$(cat "$STATE/drift-notified" 2>/dev/null)" != "$after" ]]; then
    echo "【协议副本被改过】根目录 $NAME 和正本 $AI_DIR/jaAgents/$NAME 不一致，而且副本被人改过（不是旧版本）。"
    echo "按 shelf-ops「根副本与正本」：先用 git diff --no-index $AI_DIR/jaAgents/$NAME $NAME 把差异给用户看；"
    echo "用户确认后才把改动同步回正本并 shelf push（推前同样先给清单）。确认之前两份都不要改。"
    printf '%s' "$after" > "$STATE/drift-notified"
  fi
elif [[ -n "$loaded" && "$loaded" != "$after" ]]; then
  echo "【协议已更新】本会话开场时读的根目录 $NAME 已经过期：正本 $AI_DIR/jaAgents/$NAME 改过了$( [[ "$RESULT" == refreshed ]] && echo '，副本刚已换成最新版' )。"
  echo "先用 Read 完整重读 $AI_DIR/jaAgents/$NAME，之后一律按新版执行；新版与本会话开场时的规则冲突的，以新版为准。"
fi
printf '%s' "$after" > "$SESSION_FILE"
exit 0
